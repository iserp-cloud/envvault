/**
 * Writes test/vectors/zk-6.json: fixed ciphertexts that every EnvVault implementation
 * (the TypeScript clients and the Go operator) must open to the same plaintext.
 *
 *   pnpm vectors
 *
 * Run it only when the protocol changes; the committed file is the contract.
 * The key inside is a throwaway generated for this file and protects nothing.
 */
import { writeFileSync } from "node:fs";
import {
  encodeServiceToken,
  envAad,
  generateDek,
  generateIdentityKeyPair,
  sealEnv,
  wrapSecretForPublicKey,
} from "@envvault/shared";

const out = new URL("../test/vectors/zk-6.json", import.meta.url);

const pair = await generateIdentityKeyPair();
const tenantId = "t_vectors";
const project = "my-app";
const env = "production";
const values = {
  DATABASE_URL: "postgres://user:p@ss@db.internal:5432/app?sslmode=require",
  EMPTY: "",
  MULTILINE: "line one\nline two\n",
  UNICODE: "héllo ✓ 日本語",
  API_KEY: "sk_test_0123456789",
};

const dek = generateDek();
const wrappedEnvDek = await wrapSecretForPublicKey(dek, pair.publicKey);
const payload = await sealEnv(values, dek, envAad(tenantId, project, env));
const token = encodeServiceToken({
  v: 1,
  u: "svc-vectors",
  t: "bearer-token-for-vectors",
  k: pair.privateKey,
  w: tenantId,
  r: "https://hub.example.test",
});

const vectors = {
  schema: "zk-6",
  note: "Throwaway test key. Generated by scripts/gen-vectors.ts; do not use for anything real.",
  serviceToken: token,
  tokenFields: { v: 1, u: "svc-vectors", t: "bearer-token-for-vectors", w: tenantId, r: "https://hub.example.test" },
  publicKey: pair.publicKey,
  environment: {
    tenantId,
    project,
    name: env,
    aad: envAad(tenantId, project, env),
    wrappedEnvDek,
    payload,
    expected: values,
  },
  /** Each of these must be REJECTED. */
  mustFail: {
    wrongAad: envAad(tenantId, project, "staging"),
    badVersion: { ...payload, v: 2 },
    tamperedCiphertext: { ...payload, ct: payload.ct.slice(0, -4) + (payload.ct.endsWith("AAAA") ? "BBBB" : "AAAA") },
  },
};

writeFileSync(out, JSON.stringify(vectors, null, 2) + "\n");
console.log(`wrote ${out.pathname}`);
